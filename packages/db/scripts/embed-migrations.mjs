// Embeds migrations/*.sql into src/migrations.generated.ts so bundled apps can migrate without
// shipping the folder. Run after `drizzle-kit generate` (npm run generate does both).
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const folder = join(root, 'migrations');
const journal = JSON.parse(readFileSync(join(folder, 'meta/_journal.json'), 'utf8'));
const out = journal.entries.map((e) => {
  const query = readFileSync(join(folder, `${e.tag}.sql`), 'utf8');
  return {
    tag: e.tag,
    folderMillis: e.when,
    bps: e.breakpoints,
    hash: createHash('sha256').update(query).digest('hex'),
    sql: query.split('--> statement-breakpoint'),
  };
});
const body = `// Generated by scripts/embed-migrations.mjs from migrations/. Do not edit.
export interface EmbeddedMigration {
  tag: string;
  folderMillis: number;
  bps: boolean;
  hash: string;
  sql: string[];
}

export const MIGRATIONS: readonly EmbeddedMigration[] = ${JSON.stringify(out, null, 2)};
`;
writeFileSync(join(root, 'src/migrations.generated.ts'), body);
console.log(`embedded ${out.length} migration(s)`);
